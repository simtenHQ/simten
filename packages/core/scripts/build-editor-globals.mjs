#!/usr/bin/env node
// Codegen for issue #102 Step 3.
//
// Generates dist/editor-globals.dts.txt — a non-.d.ts ambient-globals shim
// that the Monaco editor at /circuit loads via addExtraLib alongside the
// bundled core types. The shim mirrors the runtime scope injected by
// executeCircuitCode() (see circuit/execute.ts:55-73): every name that gets
// dropped into user code at execution time needs a corresponding `declare
// global { const X: ... }` entry so Monaco recognises it without an import.
//
// Source of truth: the actual `@simten/core` exports at build time. No
// hand-maintained list — re-running this picks up new stdlib components
// automatically.
//
// Why not .d.ts: a real .d.ts under apps/web/src/ would be auto-included by
// TS and its `declare global` block would leak into the rest of apps/web's
// typecheck. We hand the string to Monaco's TS worker only, so the file
// extension is irrelevant to consumption.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'dist', 'editor-globals.dts.txt');
const bundlePath = join(here, '..', 'dist', 'bundle.d.ts');

// Parse JSDoc-per-symbol out of the bundle so we can re-emit it above each
// `const X: typeof core.X` line in the globals shim. Without this step, the
// hover on `And`/`Xor`/etc. inside the Monaco editor shows only the type
// signature — TypeScript does not forward JSDoc through `typeof` lookups,
// so the JSDoc on `export const And` in the bundle never reaches the
// global binding's hover.
function extractJsDocBySymbol(dtsSource) {
  const out = new Map();
  // Matches a JSDoc block IMMEDIATELY before `declare const X` /
  // `declare function X`. The comment body is `(?:[^*]|\*(?!\/))*` — it cannot
  // cross a `*/`, so the capture is exactly one comment block. A lazy
  // `[\s\S]*?` here would, for symbols whose declaration is separated from
  // their doc by intervening `type` declarations (e.g. the RV32I_Core cast
  // pattern), swallow those declarations into the "JSDoc" and paste them
  // into `declare global {}` — where names like `Node` resolve to DOM types
  // and silently poison the editor's circuit() overload resolution.
  const re = /(\/\*\*(?:[^*]|\*(?!\/))*\*\/)\s*\ndeclare (?:const|function) (\w+)\b/g;
  let m;
  while ((m = re.exec(dtsSource)) !== null) {
    const [, jsdoc, name] = m;
    out.set(name, jsdoc);
  }
  return out;
}

const bundleSrc = readFileSync(bundlePath, 'utf8');
const jsdocBySymbol = extractJsDocBySymbol(bundleSrc);

// Import the freshly-built core stdlib to read its real exports. Must run
// after tsc. We iterate the *stdlib* surface specifically — matching what
// executeCircuitCode() injects (circuit/execute.ts:67-73) — so this shim
// never accidentally exposes non-stdlib root exports like `elaborate` or
// `executeCircuitCode` as if they were sandbox globals.
const std = await import(join(here, '..', 'dist', 'std', 'index.js'));

// Mirror executeCircuitCode's scope construction (circuit/execute.ts:55-73):
//   - Fixed core API: circuit, component (alias), bit, bus, reg, mem
//   - Every stdlib BuiltCircuit injects under value.circuit.name
//   - Every stdlib function injects under its export name
//
// For each runtime name, we emit `declare const <runtimeName>: typeof core.<exportKey>`.
// In stdlib, export key === circuit name by convention (export const And = circuit('And', ...)),
// so a single map suffices for both.

const lines = [];
lines.push('// AUTO-GENERATED by packages/core/scripts/build-editor-globals.mjs');
lines.push('// DO NOT EDIT. Regenerate via `pnpm --filter @simten/core build`.');
lines.push('//');
lines.push('// Mirrors the runtime scope injected by executeCircuitCode() so');
lines.push('// user code in the Monaco editor at /circuit can reference circuit,');
lines.push('// bit, bus, And, Or, etc. without import statements.');
lines.push('');
lines.push("import type * as core from '@simten/core';");
lines.push('');
lines.push('declare global {');

// Fixed core API. `component` is a runtime backward-compat alias for `circuit`.
lines.push('  const circuit: typeof core.circuit;');
lines.push('  const component: typeof core.circuit;');
lines.push('  const bit: typeof core.bit;');
lines.push('  const bus: typeof core.bus;');
lines.push('  const reg: typeof core.reg;');
lines.push('  const mem: typeof core.mem;');

// Walk stdlib exports the same way execute.ts:67-72 does.
const seen = new Set(['circuit', 'component', 'bit', 'bus', 'reg', 'mem']);
const circuits = [];
const helpers = [];

for (const [exportName, value] of Object.entries(std)) {
  if (seen.has(exportName)) continue;
  if (value && typeof value === 'object' && 'circuit' in value) {
    const runtimeName = value.circuit.name;
    if (seen.has(runtimeName)) continue;
    seen.add(runtimeName);
    if (runtimeName !== exportName) {
      // Sanity: stdlib convention is `export const Foo = circuit('Foo', ...)`.
      // If this fires, the codegen + execute.ts agreement has drifted.
      console.warn(
        `[editor-globals] export name "${exportName}" ≠ circuit name "${runtimeName}" — using export name for type lookup`,
      );
    }
    circuits.push({ exportName, runtimeName });
  } else if (typeof value === 'function') {
    seen.add(exportName);
    helpers.push(exportName);
  }
}

// Indent a (possibly multi-line) JSDoc block to sit inside `declare global {`.
function indentJsDoc(jsdoc) {
  return jsdoc
    .split('\n')
    .map((l) => '  ' + l)
    .join('\n');
}

if (circuits.length > 0) {
  lines.push('');
  lines.push('  // Stdlib components');
  for (const { exportName, runtimeName } of circuits) {
    const jsdoc = jsdocBySymbol.get(exportName);
    if (jsdoc) lines.push(indentJsDoc(jsdoc));
    lines.push(`  const ${runtimeName}: typeof core.${exportName};`);
  }
}

if (helpers.length > 0) {
  lines.push('');
  lines.push('  // Stdlib helpers');
  for (const name of helpers) {
    const jsdoc = jsdocBySymbol.get(name);
    if (jsdoc) lines.push(indentJsDoc(jsdoc));
    lines.push(`  const ${name}: typeof core.${name};`);
  }
}

// Import-namespace factories (Pmux/Mem/Dlatch) — shape-named primitives that
// fall out of yosys elaboration and appear in generated Verilog imports.
// Injected into the sandbox by execute.ts but NOT part of @simten/core's
// published surface, so their signatures are declared explicitly here.
lines.push('');
lines.push('  // Import-namespace factories (from generated Verilog imports)');
lines.push('  /** One-hot parallel mux — synthesized from a full `case`. */');
lines.push('  const Pmux: (opts: { width: number; sWidth: number }) => core.BuiltCircuit;');
lines.push('  /** Multi-port memory — from a `$mem_v2` cell. */');
lines.push(
  '  const Mem: (opts: { rdPorts: number; wrPorts: number; abits: number; width: number; size: number }) => core.BuiltCircuit;',
);
lines.push('  /** Inferred level-sensitive D-latch. */');
lines.push('  const Dlatch: (opts: { width: number; enPolarity: number }) => core.BuiltCircuit;');

lines.push('}');
lines.push('');
lines.push('export {};');
lines.push('');

writeFileSync(outPath, lines.join('\n'));

console.log(
  `editor-globals: ${circuits.length} components + ${helpers.length} helpers → ${outPath}`,
);
