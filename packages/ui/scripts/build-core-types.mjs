#!/usr/bin/env node
//
// Generates src/monaco/generated/core-types.gen.ts — the `@simten/core` type
// payloads inlined as string constants, ready to hand to Monaco's addExtraLib.
//
// Only @simten/ui/monaco imports the output, and it costs every other subpath
// nothing: `sideEffects: false` plus subpath exports keep it out of any bundle
// that doesn't pull in the editor.
//
// Why codegen rather than importing the .d.ts files directly:
//
// apps/web reads these with Vite's `?raw` suffix, which works because Vite
// builds the app. This package is built with `tsc -b`, which is a compiler and
// not a bundler — it would preserve `import x from '@simten/core/bundle?raw'`
// verbatim into dist/, leaving every consumer to resolve a Vite-specific query
// suffix with their own bundler. Webpack, esbuild, and Rollup consumers would
// all break, and the failure would surface in *their* build, not ours.
//
// Inlining at build time makes the payloads portable to any bundler and removes
// the runtime fetch. The cost is that the types are pinned to the @simten/core
// version this package was built against — see README, "Version coupling".
//
// Reads from core's dist/, so `pnpm --filter @simten/core build` must run first.
// `pnpm -r build` orders that correctly via the workspace dependency.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const coreDist = join(here, '..', '..', 'core', 'dist');
const outDir = join(here, '..', 'src', 'monaco', 'generated');
const outPath = join(outDir, 'core-types.gen.ts');

/** @param {string} p */
function read(p) {
  try {
    return readFileSync(p, 'utf8');
  } catch (err) {
    throw new Error(
      `Could not read ${p}\nBuild @simten/core first: pnpm --filter @simten/core build\n${err.message}`,
    );
  }
}

const bundle = read(join(coreDist, 'bundle.d.ts'));
const globals = read(join(coreDist, 'editor-globals.dts.txt'));

// JSON.stringify emits a correctly escaped double-quoted literal, which is also
// a valid TS string literal. Hand-rolling this with template literals would mean
// escaping backticks and ${ across ~150KB of generated .d.ts text.
const source = `// AUTO-GENERATED by scripts/build-core-types.mjs — do not edit.
//
// The @simten/core type payloads, inlined as strings for Monaco's addExtraLib.
// Regenerate with: pnpm --filter @simten/ui build

/** Flattened ambient bundle of the @simten/core types. */
export const SIMTEN_CORE_TYPES = ${JSON.stringify(bundle)};

/**
 * \`declare global\` shim mirroring the runtime scope injected by
 * executeCircuitCode() — lets circuit source reference \`circuit\`, \`And\`,
 * \`Adder\`, etc. with no import.
 */
export const SIMTEN_CORE_GLOBALS = ${JSON.stringify(globals)};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, source);

const kb = (s) => `${(s.length / 1024).toFixed(1)}KB`;
console.log(`build-core-types: wrote ${outPath} (bundle ${kb(bundle)}, globals ${kb(globals)})`);
