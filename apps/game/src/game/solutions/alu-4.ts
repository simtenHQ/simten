/** Reference solution for `alu-4`. Proven by `__tests__/levels.test.ts`. */

import { bit, circuit } from '@simten/core/circuit';
import { And, Led, Not, Or, Switch, Xor } from '@simten/core/std';

const Mux2 = circuit('Mux2', {
  inputs: { a: bit, b: bit, sel: bit },
  outputs: { out: bit },
  nodes: { x1: Xor, a1: And, x2: Xor },
  connect: ({ inputs, outputs, nodes: { x1, a1, x2 } }) => [
    inputs.a.to(x1.a, x2.a),
    inputs.b.to(x1.b),
    inputs.sel.to(a1.b),
    x1.out.to(a1.a),
    a1.out.to(x2.b),
    x2.out.to(outputs.out),
  ],
});

const Mux4 = circuit('Mux4', {
  inputs: { d0: bit, d1: bit, d2: bit, d3: bit, s1: bit, s0: bit },
  outputs: { out: bit },
  nodes: { low: Mux2, high: Mux2, pick: Mux2 },
  connect: ({ inputs, outputs, nodes: { low, high, pick } }) => [
    inputs.d0.to(low.a),
    inputs.d1.to(low.b),
    inputs.d2.to(high.a),
    inputs.d3.to(high.b),
    inputs.s0.to(low.sel, high.sel),
    low.out.to(pick.a),
    high.out.to(pick.b),
    inputs.s1.to(pick.sel),
    pick.out.to(outputs.out),
  ],
});

const HalfAdder = circuit('HalfAdder', {
  inputs: { a: bit, b: bit },
  outputs: { sum: bit, carry: bit },
  nodes: { x1: Xor, a1: And },
  connect: ({ inputs, outputs, nodes: { x1, a1 } }) => [
    inputs.a.to(x1.a, a1.a),
    inputs.b.to(x1.b, a1.b),
    x1.out.to(outputs.sum),
    a1.out.to(outputs.carry),
  ],
});

const FullAdder = circuit('FullAdder', {
  inputs: { a: bit, b: bit, cin: bit },
  outputs: { sum: bit, cout: bit },
  nodes: { h1: HalfAdder, h2: HalfAdder, o1: Or },
  connect: ({ inputs, outputs, nodes: { h1, h2, o1 } }) => [
    inputs.a.to(h1.a),
    inputs.b.to(h1.b),
    h1.sum.to(h2.a),
    inputs.cin.to(h2.b),
    h2.sum.to(outputs.sum),
    h1.carry.to(o1.a),
    h2.carry.to(o1.b),
    o1.out.to(outputs.cout),
  ],
});

const Adder4 = circuit('Adder4', {
  inputs: { a3: bit, a2: bit, a1: bit, a0: bit, b3: bit, b2: bit, b1: bit, b0: bit },
  outputs: { s3: bit, s2: bit, s1: bit, s0: bit, cout: bit },
  nodes: { add0: HalfAdder, add1: FullAdder, add2: FullAdder, add3: FullAdder },
  connect: ({ inputs, outputs, nodes: { add0, add1, add2, add3 } }) => [
    inputs.a0.to(add0.a),
    inputs.b0.to(add0.b),
    add0.sum.to(outputs.s0),
    add0.carry.to(add1.cin),
    inputs.a1.to(add1.a),
    inputs.b1.to(add1.b),
    add1.sum.to(outputs.s1),
    add1.cout.to(add2.cin),
    inputs.a2.to(add2.a),
    inputs.b2.to(add2.b),
    add2.sum.to(outputs.s2),
    add2.cout.to(add3.cin),
    inputs.a3.to(add3.a),
    inputs.b3.to(add3.b),
    add3.sum.to(outputs.s3),
    add3.cout.to(outputs.cout),
  ],
});

const Subtract4 = circuit('Subtract4', {
  inputs: { a3: bit, a2: bit, a1: bit, a0: bit, b3: bit, b2: bit, b1: bit, b0: bit },
  outputs: { d3: bit, d2: bit, d1: bit, d0: bit, borrow: bit },
  nodes: {
    na3: Not,
    na2: Not,
    na1: Not,
    na0: Not,
    add: Adder4,
    ns3: Not,
    ns2: Not,
    ns1: Not,
    ns0: Not,
  },
  connect: ({ inputs, outputs, nodes: { na3, na2, na1, na0, add, ns3, ns2, ns1, ns0 } }) => [
    inputs.a3.to(na3.in),
    inputs.a2.to(na2.in),
    inputs.a1.to(na1.in),
    inputs.a0.to(na0.in),
    na3.out.to(add.a3),
    na2.out.to(add.a2),
    na1.out.to(add.a1),
    na0.out.to(add.a0),
    inputs.b3.to(add.b3),
    inputs.b2.to(add.b2),
    inputs.b1.to(add.b1),
    inputs.b0.to(add.b0),
    add.s3.to(ns3.in),
    add.s2.to(ns2.in),
    add.s1.to(ns1.in),
    add.s0.to(ns0.in),
    ns3.out.to(outputs.d3),
    ns2.out.to(outputs.d2),
    ns1.out.to(outputs.d1),
    ns0.out.to(outputs.d0),
    add.cout.to(outputs.borrow),
  ],
});

// Every answer is worked out at once, and op1 op0 picks one per output bit:
// 00 add, 01 subtract, 10 AND, 11 OR, in the order the Mux4 numbers its inputs.
export const Alu4 = circuit('Alu4', {
  nodes: {
    op1: Switch,
    op0: Switch,
    a3: Switch,
    a2: Switch,
    a1: Switch,
    a0: Switch,
    b3: Switch,
    b2: Switch,
    b1: Switch,
    b0: Switch,
    add: Adder4,
    sub: Subtract4,
    and3: And,
    and2: And,
    and1: And,
    and0: And,
    or3: Or,
    or2: Or,
    or1: Or,
    or0: Or,
    pick3: Mux4,
    pick2: Mux4,
    pick1: Mux4,
    pick0: Mux4,
    r3: Led,
    r2: Led,
    r1: Led,
    r0: Led,
  },
  connect: ({
    nodes: {
      op1,
      op0,
      a3,
      a2,
      a1,
      a0,
      b3,
      b2,
      b1,
      b0,
      add,
      sub,
      and3,
      and2,
      and1,
      and0,
      or3,
      or2,
      or1,
      or0,
      pick3,
      pick2,
      pick1,
      pick0,
      r3,
      r2,
      r1,
      r0,
    },
  }) => [
    a3.out.to(add.a3, sub.a3, and3.a, or3.a),
    b3.out.to(add.b3, sub.b3, and3.b, or3.b),
    add.s3.to(pick3.d0),
    sub.d3.to(pick3.d1),
    and3.out.to(pick3.d2),
    or3.out.to(pick3.d3),
    pick3.out.to(r3.in),
    a2.out.to(add.a2, sub.a2, and2.a, or2.a),
    b2.out.to(add.b2, sub.b2, and2.b, or2.b),
    add.s2.to(pick2.d0),
    sub.d2.to(pick2.d1),
    and2.out.to(pick2.d2),
    or2.out.to(pick2.d3),
    pick2.out.to(r2.in),
    a1.out.to(add.a1, sub.a1, and1.a, or1.a),
    b1.out.to(add.b1, sub.b1, and1.b, or1.b),
    add.s1.to(pick1.d0),
    sub.d1.to(pick1.d1),
    and1.out.to(pick1.d2),
    or1.out.to(pick1.d3),
    pick1.out.to(r1.in),
    a0.out.to(add.a0, sub.a0, and0.a, or0.a),
    b0.out.to(add.b0, sub.b0, and0.b, or0.b),
    add.s0.to(pick0.d0),
    sub.d0.to(pick0.d1),
    and0.out.to(pick0.d2),
    or0.out.to(pick0.d3),
    pick0.out.to(r0.in),
    op1.out.to(pick3.s1, pick2.s1, pick1.s1, pick0.s1),
    op0.out.to(pick3.s0, pick2.s0, pick1.s0, pick0.s0),
  ],
});
