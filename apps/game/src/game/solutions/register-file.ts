/** Reference solution for `register-file`. Proven by `__tests__/levels.test.ts`. */

import { bit, circuit } from '@simten/core/circuit';
import { And, DFlipFlop, Led, Switch, Xor } from '@simten/core/std';

const RegisterBit = circuit('RegisterBit', {
  inputs: { load: bit, d: bit },
  outputs: { q: bit },
  nodes: { ff: DFlipFlop(), x1: Xor, a1: And, x2: Xor },
  connect: ({ inputs, outputs, nodes: { ff, x1, a1, x2 } }) => [
    ff.q.to(x1.a, x2.a, outputs.q),
    inputs.d.to(x1.b),
    x1.out.to(a1.a),
    inputs.load.to(a1.b),
    a1.out.to(x2.b),
    x2.out.to(ff.d),
  ],
});

const Register4 = circuit('Register4', {
  inputs: { load: bit, d3: bit, d2: bit, d1: bit, d0: bit },
  outputs: { q3: bit, q2: bit, q1: bit, q0: bit },
  nodes: { b3: RegisterBit, b2: RegisterBit, b1: RegisterBit, b0: RegisterBit },
  connect: ({ inputs, outputs, nodes: { b3, b2, b1, b0 } }) => [
    inputs.load.to(b3.load, b2.load, b1.load, b0.load),
    inputs.d3.to(b3.d),
    inputs.d2.to(b2.d),
    inputs.d1.to(b1.d),
    inputs.d0.to(b0.d),
    b3.q.to(outputs.q3),
    b2.q.to(outputs.q2),
    b1.q.to(outputs.q1),
    b0.q.to(outputs.q0),
  ],
});

// write and wsel give each register its load line: r1 loads on write AND wsel,
// and r0 on write without r1, which is write XOR that. Reading is one
// multiplexer per bit, choosing between the two registers by rsel.
export const RegFile2 = circuit('RegFile2', {
  nodes: {
    write: Switch,
    wsel: Switch,
    rsel: Switch,
    d3: Switch,
    d2: Switch,
    d1: Switch,
    d0: Switch,
    r0: Register4,
    r1: Register4,
    load1: And,
    load0: Xor,
    x3a: Xor,
    a3: And,
    x3b: Xor,
    x2a: Xor,
    a2: And,
    x2b: Xor,
    x1a: Xor,
    a1: And,
    x1b: Xor,
    x0a: Xor,
    a0: And,
    x0b: Xor,
    q3: Led,
    q2: Led,
    q1: Led,
    q0: Led,
  },
  connect: ({
    nodes: {
      write,
      wsel,
      rsel,
      d3,
      d2,
      d1,
      d0,
      r0,
      r1,
      load1,
      load0,
      x3a,
      a3,
      x3b,
      x2a,
      a2,
      x2b,
      x1a,
      a1,
      x1b,
      x0a,
      a0,
      x0b,
      q3,
      q2,
      q1,
      q0,
    },
  }) => [
    write.out.to(load1.a, load0.a),
    wsel.out.to(load1.b),
    load1.out.to(r1.load, load0.b),
    load0.out.to(r0.load),
    d3.out.to(r0.d3, r1.d3),
    d2.out.to(r0.d2, r1.d2),
    d1.out.to(r0.d1, r1.d1),
    d0.out.to(r0.d0, r1.d0),
    r0.q3.to(x3a.a, x3b.a),
    r1.q3.to(x3a.b),
    x3a.out.to(a3.a),
    a3.out.to(x3b.b),
    x3b.out.to(q3.in),
    r0.q2.to(x2a.a, x2b.a),
    r1.q2.to(x2a.b),
    x2a.out.to(a2.a),
    a2.out.to(x2b.b),
    x2b.out.to(q2.in),
    r0.q1.to(x1a.a, x1b.a),
    r1.q1.to(x1a.b),
    x1a.out.to(a1.a),
    a1.out.to(x1b.b),
    x1b.out.to(q1.in),
    r0.q0.to(x0a.a, x0b.a),
    r1.q0.to(x0a.b),
    x0a.out.to(a0.a),
    a0.out.to(x0b.b),
    x0b.out.to(q0.in),
    rsel.out.to(a3.b, a2.b, a1.b, a0.b),
  ],
});
