/** Reference solution for `register-file`. Proven by `__tests__/levels.test.ts`. */

import { bit, circuit } from '@simten/core/circuit';
import {
  And,
  Combiner,
  DFlipFlop,
  HexDisplay,
  Input,
  Splitter,
  Switch,
  Xor,
} from '@simten/core/std';

const RegisterBit = circuit('RegisterBit', {
  inputs: { load: bit, d: bit },
  outputs: { q: bit },
  nodes: { ff: DFlipFlop(), x1: Xor, a1: And, x2: Xor },
  connect: ({ inputs, outputs, nodes: { ff, x1, a1, x2 } }) => [
    ff.q.to(x1.a, x2.a, outputs.q),
    inputs.d.to(x1.b),
    x1.out.to(a1.a),
    inputs.load.to(a1.b),
    a1.out.to(x2.b),
    x2.out.to(ff.d),
  ],
});

const Register4 = circuit('Register4', {
  inputs: { load: bit, d3: bit, d2: bit, d1: bit, d0: bit },
  outputs: { q3: bit, q2: bit, q1: bit, q0: bit },
  nodes: { b3: RegisterBit, b2: RegisterBit, b1: RegisterBit, b0: RegisterBit },
  connect: ({ inputs, outputs, nodes: { b3, b2, b1, b0 } }) => [
    inputs.load.to(b3.load, b2.load, b1.load, b0.load),
    inputs.d3.to(b3.d),
    inputs.d2.to(b2.d),
    inputs.d1.to(b1.d),
    inputs.d0.to(b0.d),
    b3.q.to(outputs.q3),
    b2.q.to(outputs.q2),
    b1.q.to(outputs.q1),
    b0.q.to(outputs.q0),
  ],
});

// write and wsel give each register its load line: r1 loads on write AND wsel,
// and r0 on write without r1, which is write XOR that. Each read port is one
// multiplexer per bit, choosing between the two registers by its select.
export const RegFile2 = circuit('RegFile2', {
  nodes: {
    write: Switch,
    wsel: Switch,
    asel: Switch,
    bsel: Switch,
    d: Input({ width: 4 }),
    dBits: Splitter({ width: 4 }),
    r0: Register4,
    r1: Register4,
    load1: And,
    load0: Xor,
    a3x: Xor,
    a3n: And,
    a3y: Xor,
    a2x: Xor,
    a2n: And,
    a2y: Xor,
    a1x: Xor,
    a1n: And,
    a1y: Xor,
    a0x: Xor,
    a0n: And,
    a0y: Xor,
    b3x: Xor,
    b3n: And,
    b3y: Xor,
    b2x: Xor,
    b2n: And,
    b2y: Xor,
    b1x: Xor,
    b1n: And,
    b1y: Xor,
    b0x: Xor,
    b0n: And,
    b0y: Xor,
    a: HexDisplay({ width: 4 }),
    aBits: Combiner({ width: 4 }),
    b: HexDisplay({ width: 4 }),
    bBits: Combiner({ width: 4 }),
  },
  connect: ({
    nodes: {
      write,
      wsel,
      asel,
      bsel,
      d,
      dBits,
      r0,
      r1,
      load1,
      load0,
      a3x,
      a3n,
      a3y,
      a2x,
      a2n,
      a2y,
      a1x,
      a1n,
      a1y,
      a0x,
      a0n,
      a0y,
      b3x,
      b3n,
      b3y,
      b2x,
      b2n,
      b2y,
      b1x,
      b1n,
      b1y,
      b0x,
      b0n,
      b0y,
      a,
      aBits,
      b,
      bBits,
    },
  }) => [
    d.out.to(dBits.in),
    aBits.out.to(a.in),
    bBits.out.to(b.in),
    write.out.to(load1.a, load0.a),
    wsel.out.to(load1.b),
    load1.out.to(r1.load, load0.b),
    load0.out.to(r0.load),
    dBits.bit3.to(r0.d3, r1.d3),
    dBits.bit2.to(r0.d2, r1.d2),
    dBits.bit1.to(r0.d1, r1.d1),
    dBits.bit0.to(r0.d0, r1.d0),
    asel.out.to(a3n.b, a2n.b, a1n.b, a0n.b),
    r0.q3.to(a3x.a, a3y.a),
    r1.q3.to(a3x.b),
    a3x.out.to(a3n.a),
    a3n.out.to(a3y.b),
    a3y.out.to(aBits.bit3),
    r0.q2.to(a2x.a, a2y.a),
    r1.q2.to(a2x.b),
    a2x.out.to(a2n.a),
    a2n.out.to(a2y.b),
    a2y.out.to(aBits.bit2),
    r0.q1.to(a1x.a, a1y.a),
    r1.q1.to(a1x.b),
    a1x.out.to(a1n.a),
    a1n.out.to(a1y.b),
    a1y.out.to(aBits.bit1),
    r0.q0.to(a0x.a, a0y.a),
    r1.q0.to(a0x.b),
    a0x.out.to(a0n.a),
    a0n.out.to(a0y.b),
    a0y.out.to(aBits.bit0),
    bsel.out.to(b3n.b, b2n.b, b1n.b, b0n.b),
    r0.q3.to(b3x.a, b3y.a),
    r1.q3.to(b3x.b),
    b3x.out.to(b3n.a),
    b3n.out.to(b3y.b),
    b3y.out.to(bBits.bit3),
    r0.q2.to(b2x.a, b2y.a),
    r1.q2.to(b2x.b),
    b2x.out.to(b2n.a),
    b2n.out.to(b2y.b),
    b2y.out.to(bBits.bit2),
    r0.q1.to(b1x.a, b1y.a),
    r1.q1.to(b1x.b),
    b1x.out.to(b1n.a),
    b1n.out.to(b1y.b),
    b1y.out.to(bBits.bit1),
    r0.q0.to(b0x.a, b0y.a),
    r1.q0.to(b0x.b),
    b0x.out.to(b0n.a),
    b0n.out.to(b0y.b),
    b0y.out.to(bBits.bit0),
  ],
});
