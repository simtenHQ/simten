/** Reference solution for `program-counter`. Proven by `__tests__/levels.test.ts`. */

import { circuit } from '@simten/core/circuit';
import { And, DFlipFlop, Led, Switch, Xor } from '@simten/core/std';

export const ProgramCounter4 = circuit('ProgramCounter4', {
  nodes: {
    jump: Switch,
    a3: Switch,
    a2: Switch,
    a1: Switch,
    a0: Switch,
    ff3: DFlipFlop(),
    ff2: DFlipFlop(),
    ff1: DFlipFlop(),
    ff0: DFlipFlop(),
    inc1: Xor,
    carry2: And,
    inc2: Xor,
    carry3: And,
    inc3: Xor,
    x3a: Xor,
    j3: And,
    x3b: Xor,
    x2a: Xor,
    j2: And,
    x2b: Xor,
    x1a: Xor,
    j1: And,
    x1b: Xor,
    x0a: Xor,
    j0: And,
    x0b: Xor,
    pc3: Led,
    pc2: Led,
    pc1: Led,
    pc0: Led,
  },
  connect: ({
    nodes: {
      jump,
      a3,
      a2,
      a1,
      a0,
      ff3,
      ff2,
      ff1,
      ff0,
      inc1,
      carry2,
      inc2,
      carry3,
      inc3,
      x3a,
      j3,
      x3b,
      x2a,
      j2,
      x2b,
      x1a,
      j1,
      x1b,
      x0a,
      j0,
      x0b,
      pc3,
      pc2,
      pc1,
      pc0,
    },
  }) => [
    // Add one: bit 0 always flips, and each bit above flips when every bit
    // below it is 1.
    ff0.q.to(pc0.in, inc1.b, carry2.b),
    ff1.q.to(pc1.in, inc1.a, carry2.a),
    ff2.q.to(pc2.in, inc2.a, carry3.a),
    ff3.q.to(pc3.in, inc3.a),
    carry2.out.to(inc2.b, carry3.b),
    carry3.out.to(inc3.b),

    // Then each bit picks the count or the jump address, a multiplexer as
    // inc XOR (jump AND (inc XOR a)).
    jump.out.to(j3.b, j2.b, j1.b, j0.b),
    inc3.out.to(x3a.a, x3b.a),
    a3.out.to(x3a.b),
    x3a.out.to(j3.a),
    j3.out.to(x3b.b),
    x3b.out.to(ff3.d),
    inc2.out.to(x2a.a, x2b.a),
    a2.out.to(x2a.b),
    x2a.out.to(j2.a),
    j2.out.to(x2b.b),
    x2b.out.to(ff2.d),
    inc1.out.to(x1a.a, x1b.a),
    a1.out.to(x1a.b),
    x1a.out.to(j1.a),
    j1.out.to(x1b.b),
    x1b.out.to(ff1.d),
    ff0.q_bar.to(x0a.a, x0b.a),
    a0.out.to(x0a.b),
    x0a.out.to(j0.a),
    j0.out.to(x0b.b),
    x0b.out.to(ff0.d),
  ],
});
